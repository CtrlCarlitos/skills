"""Locate an existing changelog file, detect a machine-generated marker
(so a skill run never hand-edits a file something else owns), and insert a
new top section while preserving everything already there.
"""
import re
from pathlib import Path

CANDIDATE_NAMES = ("CHANGELOG.md", "CHANGES.md", "HISTORY.md", "NEWS.md")

GENERATED_MARKER_RE = re.compile(
    r"(generated by|auto-?generated).{0,80}(do not edit|don't edit)",
    re.IGNORECASE | re.DOTALL,
)

VERSION_HEADING_RE = re.compile(r"^## ", re.MULTILINE)


def find_changelog(repo_root: Path) -> Path | None:
    for name in CANDIDATE_NAMES:
        candidate = repo_root / name
        if candidate.is_file():
            return candidate
    return None


def is_generated(content: str) -> bool:
    return bool(GENERATED_MARKER_RE.search(content))


def insert_section_at_top(existing: str | None, new_section: str) -> str:
    if existing is None:
        return f"# Changelog\n\n{new_section}"

    match = VERSION_HEADING_RE.search(existing)
    if match is None:
        separator = "" if existing.endswith("\n\n") else ("\n" if existing.endswith("\n") else "\n\n")
        return f"{existing}{separator}{new_section}"

    insert_at = match.start()
    before, after = existing[:insert_at], existing[insert_at:]
    if not before.endswith("\n\n"):
        before = before.rstrip("\n") + "\n\n"
    return f"{before}{new_section}\n{after}"
