"""Tests for the gather() entrypoint that wires range resolution, commit
gathering, repo-type guide resolution, and changelog-file detection into
one call -- the single "run this first" step before any agent judgment
about which entry goes where. Uses a real git repo fixture, the same as
test_range.py and test_commits.py.

Run from skills/release-notes/: python3 -m unittest discover -s tests
"""
import subprocess
import tempfile
import unittest
from pathlib import Path

from scripts.gather import gather


def _run(args, cwd):
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True)


def _init_repo(root: Path) -> None:
    _run(["git", "init", "-q", "-b", "main"], root)
    _run(["git", "config", "user.email", "x@x.com"], root)
    _run(["git", "config", "user.name", "x"], root)


def _commit(root: Path, message: str, filename: str = "file.txt") -> None:
    (root / filename).write_text(message, encoding="utf-8")
    _run(["git", "add", "-A"], root)
    _run(["git", "commit", "-q", "-m", message], root)


class GatherTests(unittest.TestCase):
    def test_gathers_range_commits_and_type_guide_for_a_generic_repo(self):
        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as home, \
                tempfile.TemporaryDirectory() as builtin_dir:
            root, home, builtin_dir = Path(root), Path(home), Path(builtin_dir)
            _init_repo(root)
            _commit(root, "first")
            _run(["git", "tag", "v1.0.0"], root)
            _commit(root, "feat: add retry logic (#101)")
            (builtin_dir / "generic.md").write_text("# generic guide\n", encoding="utf-8")

            result = gather(root, home=home, builtin_dir=builtin_dir)

            self.assertEqual(result["range"]["base"], "v1.0.0")
            self.assertEqual([c["subject"] for c in result["commits"]], ["feat: add retry logic (#101)"])
            self.assertEqual(result["commits"][0]["pr_reference"], 101)
            self.assertEqual(result["repo_type"]["guide"], "# generic guide\n")
            self.assertIsNone(result["changelog"]["path"])
            self.assertFalse(result["changelog"]["generated"])

    def test_excludes_a_fully_collapsed_revert_pair_from_commits(self):
        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as home, \
                tempfile.TemporaryDirectory() as builtin_dir:
            root, home, builtin_dir = Path(root), Path(home), Path(builtin_dir)
            _init_repo(root)
            _commit(root, "base")
            _run(["git", "tag", "v1.0.0"], root)
            _commit(root, "feat: add thing")
            _run(["git", "revert", "--no-edit", "HEAD"], root)
            (builtin_dir / "generic.md").write_text("# generic guide\n", encoding="utf-8")

            result = gather(root, home=home, builtin_dir=builtin_dir)

            self.assertEqual(result["commits"], [])
            self.assertEqual(len(result["not_included"]), 2)

    def test_reports_an_existing_changelog_and_whether_its_generated(self):
        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as home, \
                tempfile.TemporaryDirectory() as builtin_dir:
            root, home, builtin_dir = Path(root), Path(home), Path(builtin_dir)
            _init_repo(root)
            (root / "CHANGELOG.md").write_text(
                "# Changelog\n\nGenerated by `scripts/changelog.sh` - do not edit by hand.\n",
                encoding="utf-8",
            )
            _run(["git", "add", "-A"], root)
            _run(["git", "commit", "-q", "-m", "first"], root)
            _run(["git", "tag", "v1.0.0"], root)
            _commit(root, "feat: add retry logic")
            (builtin_dir / "generic.md").write_text("# generic guide\n", encoding="utf-8")

            result = gather(root, home=home, builtin_dir=builtin_dir)

            self.assertEqual(result["changelog"]["path"], str(root / "CHANGELOG.md"))
            self.assertTrue(result["changelog"]["generated"])

    def test_raises_the_same_range_error_when_no_tag_exists(self):
        from scripts.range import RangeError

        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as home, \
                tempfile.TemporaryDirectory() as builtin_dir:
            root, home, builtin_dir = Path(root), Path(home), Path(builtin_dir)
            _init_repo(root)
            _commit(root, "first")

            with self.assertRaises(RangeError):
                gather(root, home=home, builtin_dir=builtin_dir)


if __name__ == "__main__":
    unittest.main()
