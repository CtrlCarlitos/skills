"""Tests for locating an existing changelog file, detecting a
machine-generated marker (confirmed real-world necessity: CtrlCarlitos/dotfiles'
actual CHANGELOG.md says "Generated by `scripts/changelog.sh` from git
history - do not edit by hand"), and inserting a new section at the top
while preserving existing entries.

Run from skills/release-notes/: python3 -m unittest discover -s tests
"""
import tempfile
import unittest
from pathlib import Path

from scripts.changelog_file import find_changelog, insert_section_at_top, is_generated


class FindChangelogTests(unittest.TestCase):
    def test_finds_an_existing_changelog_md_in_the_repo_root(self):
        with tempfile.TemporaryDirectory() as root:
            root = Path(root)
            (root / "CHANGELOG.md").write_text("# Changelog\n", encoding="utf-8")

            self.assertEqual(find_changelog(root), root / "CHANGELOG.md")

    def test_falls_back_to_other_common_names_when_changelog_md_is_absent(self):
        with tempfile.TemporaryDirectory() as root:
            root = Path(root)
            (root / "HISTORY.md").write_text("# History\n", encoding="utf-8")

            self.assertEqual(find_changelog(root), root / "HISTORY.md")

    def test_returns_none_when_no_changelog_file_exists(self):
        with tempfile.TemporaryDirectory() as root:
            root = Path(root)

            self.assertIsNone(find_changelog(root))


class IsGeneratedTests(unittest.TestCase):
    def test_detects_the_real_dotfiles_generated_marker(self):
        content = (
            "# Changelog\n\n"
            "Generated by `scripts/changelog.sh` from git history - do not edit by hand.\n\n"
            "## [1.0.0] - 2026-01-01\n"
        )

        self.assertTrue(is_generated(content))

    def test_detects_an_auto_generated_marker_in_a_different_phrasing(self):
        content = "# Changelog\n\nThis file is auto-generated. Do not edit directly.\n"

        self.assertTrue(is_generated(content))

    def test_a_normal_handwritten_changelog_is_not_flagged_as_generated(self):
        content = (
            "# Changelog\n\n"
            "All notable changes to this project are documented here.\n\n"
            "## [1.0.0] - 2026-01-01\n### Added\n- Initial release\n"
        )

        self.assertFalse(is_generated(content))


class InsertSectionAtTopTests(unittest.TestCase):
    def test_inserts_before_the_first_existing_version_heading(self):
        existing = (
            "# Changelog\n\n"
            "All notable changes to this project are documented here.\n\n"
            "## [1.0.0] - 2026-01-01\n### Added\n- Initial release\n"
        )
        new_section = "## [1.1.0] - 2026-02-01\n### Added\n- A new thing\n"

        result = insert_section_at_top(existing, new_section)

        self.assertIn(new_section, result)
        new_index = result.index("## [1.1.0]")
        old_index = result.index("## [1.0.0]")
        self.assertLess(new_index, old_index)
        self.assertIn("All notable changes", result)

    def test_appends_after_the_title_when_there_are_no_existing_entries_yet(self):
        existing = "# Changelog\n\nAll notable changes to this project are documented here.\n"
        new_section = "## [1.0.0] - 2026-01-01\n### Added\n- Initial release\n"

        result = insert_section_at_top(existing, new_section)

        self.assertIn("All notable changes", result)
        self.assertIn(new_section, result)
        self.assertLess(result.index("All notable changes"), result.index("## [1.0.0]"))

    def test_creates_a_fresh_changelog_when_there_is_no_existing_content(self):
        result = insert_section_at_top(None, "## [1.0.0] - 2026-01-01\n### Added\n- Initial release\n")

        self.assertIn("# Changelog", result)
        self.assertIn("## [1.0.0]", result)


if __name__ == "__main__":
    unittest.main()
