"""Tests for detecting a machine-generated doc (Rule 4: "generated docs go
through their generator" -- never hand-edited, regardless of ecosystem).
Broader than release-notes' changelog marker detection: covers the common
real-world phrasings from docstring/API-doc generators, not just a
changelog's own "do not edit by hand" convention.

Run from skills/update-docs/: python3 -m unittest discover -s tests
"""
import unittest

from scripts.generated_docs import is_generated


class IsGeneratedTests(unittest.TestCase):
    def test_detects_the_common_auto_generated_file_do_not_edit_banner(self):
        content = "<!-- AUTO-GENERATED FILE. DO NOT EDIT. -->\n\n# API Reference\n"

        self.assertTrue(is_generated(content))

    def test_detects_a_generated_by_tool_name_do_not_edit_phrasing(self):
        content = "# Reference\n\nGenerated by `dart doc`. Do not edit directly.\n"

        self.assertTrue(is_generated(content))

    def test_detects_a_this_file_is_generated_phrasing(self):
        content = "<!-- This file is generated. Any changes will be overwritten. -->\n# Foo\n"

        self.assertTrue(is_generated(content))

    def test_detects_a_do_not_modify_phrasing_as_an_alternative_to_do_not_edit(self):
        content = "# Foo\n\nThis document is auto-generated; do not modify by hand.\n"

        self.assertTrue(is_generated(content))

    def test_a_normal_handwritten_doc_is_not_flagged(self):
        content = "# Getting started\n\nInstall the package and run `make build`.\n"

        self.assertFalse(is_generated(content))

    def test_mentioning_generation_in_passing_without_a_do_not_edit_marker_is_not_flagged(self):
        """Prose that merely explains there's a generator elsewhere isn't
        the same as this specific file being its output."""
        content = "# Contributing\n\nThe API reference docs are generated from docstrings; see CONTRIBUTING.md.\n"

        self.assertFalse(is_generated(content))


if __name__ == "__main__":
    unittest.main()
