"""Detect a machine-generated doc (Rule 4: generated docs go through
their generator -- README from docstrings, `go doc`, ExDoc, `dart doc`,
rustdoc -- never hand-edited). Broader than release-notes' changelog
marker: covers the common real-world "AUTO-GENERATED FILE. DO NOT EDIT."
style banners various doc generators emit, not just a changelog script's
own convention.
"""
import re

GENERATED_MARKER_RE = re.compile(
    r"(generated by|auto-?generated|this (?:file|document) is generated)"
    r".{0,80}(do not edit|don't edit|do not modify|will be overwritten)",
    re.IGNORECASE | re.DOTALL,
)


def is_generated(content: str) -> bool:
    return bool(GENERATED_MARKER_RE.search(content))
